CREATE TABLE IF NOT EXISTS ordens_producao (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id INTEGER NOT NULL REFERENCES empresas(id) ON DELETE CASCADE,
 quote_id INTEGER NULL REFERENCES orcamentos(id) ON DELETE SET NULL,
 reference VARCHAR(120) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'ABERTA',
 model_code VARCHAR(40) NOT NULL,
 input_snapshot TEXT NOT NULL,
 technical_snapshot TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_op_company_status ON ordens_producao(company_id,status);
CREATE INDEX IF NOT EXISTS ix_op_quote ON ordens_producao(quote_id);
